#ifndef RUNNER_WINDOWS_AUTOSTART_H_
#define RUNNER_WINDOWS_AUTOSTART_H_

// Автозапуск Windows в двух видах.
//
// Обычный — значение в HKCU\...\Run: его пишет и стирает сам процесс, прав не
// нужно, но и приложение стартует неповышенным. Для TUN этого мало: после
// каждого входа в систему пришлось бы жать «Запустить от имени администратора»
// и подтверждать UAC.
//
// Повышенный — задача планировщика с RunLevel=HighestAvailable. Такую задачу
// Windows запускает уже с правами администратора и ничего не спрашивает.
// Платится это одним подтверждением UAC в момент, когда задачу создают:
// зарегистрировать её может только администратор.
//
// Оба вида одновременно не включаются: приложение стартовало бы дважды.

// Приводит автозапуск к заданному виду.
//
// [allow_elevation] разрешает показать UAC. При старте приложения он снят:
// спрашивать пароль на каждом запуске — ровно то, от чего эта настройка
// избавляет. Возвращает false, если задачу не удалось создать или удалить
// (UAC отклонили, нет прав); ключ Run к этому моменту уже выставлен так, чтобы
// автозапуск не пропал совсем.
bool KeqdroidApplyAutostart(bool enabled, bool elevated, bool allow_elevation);

// Есть ли задача планировщика, поднимающая именно этот exe. Перенесли папку с
// приложением — задача указывает на старый путь, и это уже не автозапуск.
bool KeqdroidIsAutostartElevated();

// Есть ли значение в ключе Run.
bool KeqdroidIsAutostartEnabled();

#endif  // RUNNER_WINDOWS_AUTOSTART_H_
