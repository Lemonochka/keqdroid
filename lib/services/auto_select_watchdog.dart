import 'dart:io';

/// Сторож автовыбора: замечает, что текущий сервер перестал работать.
///
/// Смена сети сама по себе поводом для переезда не считается — она только
/// причина, по которой сервер может отвалиться (белые списки в чужом Wi-Fi,
/// мобильный оператор, домашний провайдер). Решает всегда одно: отвечает
/// туннель или нет.
///
/// Проба идёт через локальный инбаунд, то есть через живое соединение, а не
/// мимо него: пакет приложения исключён из TUN, и прямой запрос сказал бы
/// только «интернет у телефона есть», что к состоянию туннеля отношения не
/// имеет.
abstract final class AutoSelectWatchdog {
  /// Как часто приложение смотрит на счётчик отказов ядра.
  ///
  /// Это не проба и не сеть: читается число в памяти процесса, которое натив
  /// насчитал по логу ядра (оба ядра сами пишут о неудачном дозвоне до
  /// сервера). Поэтому и часто — радио от этого не просыпается, а каждая
  /// секунда здесь — секунда без интернета у человека.
  static const listenEvery = Duration(seconds: 1);

  /// Сколько отказов дозвона между двумя взглядами — повод проверить сервер
  /// по-настоящему.
  ///
  /// Один. Сначала было три за секунду, и на живом тесте это не сработало
  /// ни разу: xray на Hysteria2 роняет отказы по одному раз в 16–50 секунд —
  /// каждый ждёт таймаут QUIC. Отказ в логе ядра появляется только после
  /// того, как ядро само сдалось, так что это уже весомый сигнал, а от
  /// ложной тревоги защищает проба: живой сервер на неё ответит.
  static const failureBurst = 1;

  /// Сколько секунд подряд «ушло, но ничего не пришло» — повод проверить
  /// сервер.
  ///
  /// Это главный и самый быстрый сигнал. Сервис каждую секунду знает, сколько
  /// байт ядро отправило в сеть и сколько получило. На живом сервере любое
  /// отправленное вызывает хоть что-то в ответ — данные или хотя бы
  /// TCP-подтверждения. На мёртвом приложения продолжают слать, а в ответ не
  /// приходит ни байта, и видно это через секунды, а не через таймаут ядра.
  /// Три подряд — чтобы одна неудачная секунда (спящее радио, переезд сети)
  /// не будила проверку.
  static const silentSecondsBeforeCheck = 3;

  /// Секунда, в которую ядро отправляло, но ничего не получило.
  static bool isSilentSecond({required int sent, required int received}) =>
      sent > 0 && received == 0;

  /// Сколько молчать после проверки, которая сервер не сменила.
  ///
  /// Иначе без сети вовсе (метро, самолёт) собственные пробы сторожа и
  /// отказы приложений будили бы проверку каждые две секунды, а каждая
  /// проверка — это запрос мимо туннеля.
  static const quietAfterCheck = Duration(seconds: 15);

  /// Сколько молчать после переезда.
  ///
  /// Короче, чем после проверки без переезда: новое ядро поднимается за
  /// секунду, и если новый сервер тоже мёртв, пятнадцать секунд глухоты —
  /// это пятнадцать секунд без интернета. А пяти хватает, чтобы разрыв
  /// самого переезда не приняли за новую смерть.
  static const quietAfterSwitch = Duration(seconds: 5);

  /// Страховка на случай, которого прослушка не видит.
  ///
  /// Раз в полминуты сторож смотрит, пришёл ли через туннель хоть байт, и
  /// только если нет — идёт проверять (см. [shouldProbe]). Именно пришёл:
  /// отправленные байты доказательством жизни не считаются — в мёртвый
  /// туннель приложения шлют исправно, и на живом тесте страховка молчала
  /// ровно поэтому.
  static const probeEvery = Duration(seconds: 30);

  /// Сколько независимых подтверждений нужно, прежде чем менять сервер.
  ///
  /// Не одно: короткий провал бывает у живого сервера (переезд с Wi-Fi на
  /// LTE, спящее радио, секунда без сети в лифте), а смена сервера — это
  /// разрыв соединения, и платить им за каждую случайность нельзя.
  ///
  /// Всплеск отказов, замеченный прослушкой, — уже одно подтверждение: это
  /// настоящие приложения, у которых не открылось несколько соединений
  /// подряд. После него хватает одной неудачной пробы, и вторая, с паузой
  /// между ними, нужна только страховочному тику, у которого, кроме тишины в
  /// туннеле, доказательств нет.
  static const failuresBeforeSwitch = 2;

  /// Пауза между первой неудачной пробой и второй — только у страховочного
  /// тика. Трёх секунд хватает, чтобы пережить моргнувшую сеть.
  static const retryAfterFailure = Duration(seconds: 3);

  /// Сколько ждём ответа от пробы.
  ///
  /// Живой сервер отдаёт пустой ответ через туннель за полсекунды-секунду
  /// даже на плохом LTE. Проба при этом идёт не на пустом месте, а после
  /// того, как ядро само сообщило об отказах, — и сервер, который в такой
  /// момент не может ответить за три секунды, хуже любого живого соседа.
  static const probeTimeout = Duration(seconds: 3);

  /// Идти ли в сеть на этом тике.
  ///
  /// [trafficMoved] — пришли ли байты с прошлого тика. Пришли — значит сервер
  /// отвечает, и проба была бы тратой батареи на доказательство уже
  /// доказанного.
  static bool shouldProbe({
    required bool connected,
    required bool autoSelectOn,
    required bool trafficMoved,
  }) =>
      connected && autoSelectOn && !trafficMoved;

  /// Похожи ли новые отказы дозвона на мёртвый сервер.
  static bool dialFailuresSuggestDeadServer(int newFailures) =>
      newFailures >= failureBurst;

  /// Похожа ли череда тихих секунд на мёртвый сервер.
  static bool trafficStalled(int silentSeconds) =>
      silentSeconds >= silentSecondsBeforeCheck;

  /// Пора ли съезжать на другой сервер.
  static bool shouldSwitch(int consecutiveFailures) =>
      consecutiveFailures >= failuresBeforeSwitch;

  /// Есть ли у устройства сеть вообще, мимо туннеля.
  ///
  /// Нужно, чтобы не винить сервер в том, чего он не делал: в метро, в
  /// самолёте и на нулевом сигнале не отвечает никто, и перебор серверов там
  /// означал бы разрыв за разрывом на ровном месте. Запрос идёт напрямую —
  /// пакет приложения и так исключён из туннеля.
  static Future<bool> networkResponds({
    required String testUrl,
    Duration timeout = probeTimeout,
  }) async {
    final client = HttpClient()..connectionTimeout = timeout;
    // Явный отказ от прокси: findProxy по умолчанию читает переменные
    // окружения, и на десктопе системный прокси увёл бы пробу не туда.
    client.findProxy = (_) => 'DIRECT';
    try {
      final request = await client.getUrl(Uri.parse(testUrl)).timeout(timeout);
      final response = await request.close().timeout(timeout);
      await response.drain<void>();
      return true;
    } catch (_) {
      return false;
    } finally {
      client.close(force: true);
    }
  }

  /// Отвечает ли что-нибудь через локальный инбаунд туннеля.
  ///
  /// Ответ любого кода считается успехом: нам важно, что запрос дошёл и
  /// вернулся, а не что именно ответил сайт. Провал — это исключение:
  /// инбаунд не принял, ядро не дозвонилось, время вышло.
  static Future<bool> tunnelResponds({
    required int httpPort,
    required String testUrl,
    String username = '',
    String password = '',
    Duration timeout = probeTimeout,
  }) async {
    final client = HttpClient()
      ..connectionTimeout = timeout
      // `PROXY host:port` — единственное, что понимает findProxy у dart:io:
      // SOCKS он не умеет вовсе, поэтому ходим в HTTP-инбаунд.
      ..findProxy = (_) => 'PROXY 127.0.0.1:$httpPort';
    if (username.isNotEmpty) {
      client.addProxyCredentials(
        '127.0.0.1',
        httpPort,
        '',
        HttpClientBasicCredentials(username, password),
      );
    }
    try {
      final request = await client
          .getUrl(Uri.parse(testUrl))
          .timeout(timeout);
      final response = await request.close().timeout(timeout);
      await response.drain<void>();
      return true;
    } catch (_) {
      return false;
    } finally {
      client.close(force: true);
    }
  }
}
