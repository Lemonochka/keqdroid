/// Сторож автовыбора: замечает, что текущий сервер перестал работать.
///
/// Смена сети сама по себе поводом для переезда не считается — она только
/// причина, по которой сервер может отвалиться (белые списки в чужом Wi-Fi,
/// мобильный оператор, домашний провайдер).
///
/// Устроен в два этажа. Первый — тихая прослушка: раз в секунду, без сети,
/// смотрит на трафик ядра и на отказы в его логе. Второй — судья: настоящий
/// замер текущего сервера и его соседей тем же url-пингом, что и в списке
/// серверов. Прослушка только будит судью, а решает всегда замер: уйти с
/// сервера можно, только если он сам не ответил, и только на тот, который
/// ответил прямо сейчас (см. AutoServerSelect.judge).
abstract final class AutoSelectWatchdog {
  /// Как часто прослушка смотрит на трафик и счётчик отказов.
  ///
  /// Это не проба и не сеть: читаются числа из памяти процесса. Поэтому и
  /// часто — радио от этого не просыпается, а каждая секунда здесь — секунда
  /// без интернета у человека.
  static const listenEvery = Duration(seconds: 1);

  /// Сколько новых отказов дозвона в логе ядра — повод позвать судью.
  ///
  /// Один. Сначала было три за секунду, и на живом тесте это не сработало
  /// ни разу: xray на Hysteria2 роняет отказы по одному раз в 16–50 секунд —
  /// каждый ждёт таймаут QUIC. Отказ появляется только после того, как ядро
  /// само сдалось, а от ложной тревоги защищает замер.
  static const failureBurst = 1;

  /// Сколько секунд подряд «ушло, но ничего не пришло» — повод позвать судью.
  ///
  /// Главный и самый быстрый сигнал. Сервис каждую секунду знает, сколько
  /// байт ядро отправило в сеть и сколько получило. На живом сервере любое
  /// отправленное вызывает хоть что-то в ответ — данные или хотя бы
  /// TCP-подтверждения. На мёртвом приложения продолжают слать, а в ответ не
  /// приходит ни байта. Три подряд — чтобы одна неудачная секунда (спящее
  /// радио, переезд сети) не будила судью.
  static const silentSecondsBeforeCheck = 3;

  /// Таймаут замера, секунд.
  ///
  /// Замер у судьи тот же, что в списке, но короче: мерим не «насколько
  /// быстр», а «жив ли прямо сейчас». Живой сервер отвечает за доли секунды
  /// даже на плохом LTE; четыре — запас на загруженный канал.
  static const judgeTimeoutSeconds = 4;

  /// Сколько серверов мерить за раз: текущий и лучшие из соседей.
  ///
  /// Десяток на Android — ровно одно ядро замера (общий конфиг), на
  /// десктопе — одна волна параллельных проб.
  static const candidateLimit = 10;

  /// Сколько молчать после замера, который сервер не сменил.
  ///
  /// Иначе без сети вовсе (метро, самолёт) отказы приложений будили бы замер
  /// каждую секунду, а каждый замер — это запуск ядра и десяток запросов.
  static const quietAfterCheck = Duration(seconds: 15);

  /// Сколько молчать после переезда.
  ///
  /// Короче, чем после замера без переезда: новое ядро поднимается за
  /// секунду, и если новый сервер тоже умрёт, пятнадцать секунд глухоты —
  /// это пятнадцать секунд без интернета. А пяти хватает, чтобы разрыв
  /// самого переезда не приняли за новую смерть.
  static const quietAfterSwitch = Duration(seconds: 5);

  /// Страховка на случай, которого прослушка не видит.
  ///
  /// Раз в полминуты сторож смотрит, пришёл ли через туннель хоть байт, и
  /// только если нет — зовёт судью (см. [shouldProbe]). Именно пришёл:
  /// отправленные байты доказательством жизни не считаются — в мёртвый
  /// туннель приложения шлют исправно, и на живом тесте страховка молчала
  /// ровно поэтому.
  static const probeEvery = Duration(seconds: 30);

  /// Не больше стольких переездов за [switchWindow].
  ///
  /// Последний предохранитель на случай, которого никто не предусмотрел: если
  /// замер почему-то раз за разом не видит живой сервер живым, сторож не
  /// будет гонять подключение по кругу, а отойдёт в сторону до конца окна.
  /// Три переезда за три минуты — это уже не «сервер умер», а что-то не так
  /// с самим сторожем или с сетью, и человеку лучше решить самому.
  static const maxSwitchesPerWindow = 3;
  static const switchWindow = Duration(minutes: 3);

  /// Идти ли к судье на страховочном тике.
  ///
  /// [trafficMoved] — пришли ли байты с прошлого тика. Пришли — значит сервер
  /// отвечает, и замер был бы тратой батареи на доказательство уже
  /// доказанного.
  static bool shouldProbe({
    required bool connected,
    required bool autoSelectOn,
    required bool trafficMoved,
  }) =>
      connected && autoSelectOn && !trafficMoved;

  /// Похожи ли новые отказы дозвона на мёртвый сервер.
  static bool dialFailuresSuggestDeadServer(int newFailures) =>
      newFailures >= failureBurst;

  /// Секунда, в которую ядро отправляло, но ничего не получило.
  static bool isSilentSecond({required int sent, required int received}) =>
      sent > 0 && received == 0;

  /// Похожа ли череда тихих секунд на мёртвый сервер.
  static bool trafficStalled(int silentSeconds) =>
      silentSeconds >= silentSecondsBeforeCheck;

  /// Можно ли ещё один переезд, учитывая уже сделанные ([recent]).
  static bool switchAllowed(List<DateTime> recent, DateTime now) {
    final inWindow = recent.where((t) => now.difference(t) < switchWindow);
    return inWindow.length < maxSwitchesPerWindow;
  }
}
