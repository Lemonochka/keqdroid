// налив от кнопки цепочкой форм из LiquidWaveSim. гребни к концу тормозят до нуля, последняя форма
// совпадает со стоячей картинкой, на которую виджет её потом меняет
String _pourWater(_Kind k, _Layer l, _State from, _State to) {
  final xs = _waterXs(k);
  final sim = LiquidWaveSim()..splashAt = k.button.dx / k.w;
  sim.snap(from.phase, k.levels, 0);
  final target = k.levels.target(to.phase, 0);
  const frameDt = _pourSeconds / _pourFrames;
  final bottom = k.h;
  final frames = <String>[];
  for (var f = 0; f <= _pourFrames; f++) {
    if (f > 0) {
      for (var s = 0; s < 6; s++) {
        sim.step(frameDt / 6, to.phase, k.levels, 0);
      }
    }
    final t = f * frameDt;
    final ramp = Curves.easeOut.transform(min(1.0, t / 0.8));
    final amp = from.amp + (to.amp - from.amp) * ramp;
    final phase = l.phase -
        l.pace * to.speed * _pourSeconds / 2 * pow(1 - t / _pourSeconds, 2);
    final last = f == _pourFrames;
    if (last) {
      final rest = [
        for (final x in xs) (sim.levelAt((x / k.w).clamp(0.0, 1.0)) - target).abs(),
      ].reduce(max);
      expect(rest * k.h, lessThan(1.2),
          reason: '${k.name} ${l.name}: the pour has not settled');
    }
    frames.add(_waterPath(
      k,
      l,
      xs,
      (x) => last ? target : sim.levelAt((x / k.w).clamp(0.0, 1.0)),
      amp,
      phase,
      bottom: bottom,
    ));
  }
  expect(frames.last, _stillPath(k, l, to),
      reason: '${k.name} ${l.name}: the pour does not end on the still picture');
  final morphs = StringBuffer();
  for (var f = 0; f < _pourFrames; f++) {
    morphs.write('''
                <objectAnimator
                    android:duration="${(frameDt * 1000).round()}"
                    android:interpolator="@android:anim/linear_interpolator"
                    android:propertyName="pathData"
                    android:valueFrom="${frames[f]}"
                    android:valueTo="${frames[f + 1]}"
                    android:valueType="pathType" />
''');
  }
  return '''
<?xml version="1.0" encoding="utf-8"?>
$_header
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt">
    <aapt:attr name="android:drawable">
${_vectorOpen(k.w, k.h)}
            <path
                android:name="water"
                android:fillColor="#FFFFFFFF"
                android:fillAlpha="${_n(min(1.0, to.alpha * l.alpha))}"
                android:pathData="${frames.last}" />
        </vector>
    </aapt:attr>
    <target android:name="water">
        <aapt:attr name="android:animation">
            <set android:ordering="sequentially">
$morphs            </set>
        </aapt:attr>
    </target>
</animated-vector>
''';
}

