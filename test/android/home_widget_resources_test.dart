String _logoWavePath() {
  final b = StringBuffer();
  for (var i = 0; i <= 180; i++) {
    final a = (_tail + 2.0 * i) * pi / 180;
    final r = 9.39 + 0.6945 * cos(9 * (a - 25 * pi / 180));
    b.write('${i == 0 ? 'M' : 'L'}${_n(12 + r * cos(a))},${_n(12 + r * sin(a))} ');
  }
  return b.toString().trim();
}

String _logoTrackPath() {
  final a = _tail * pi / 180;
  final x = 12 + 10.07 * cos(a);
  final y = 12 + 10.07 * sin(a);
