String _n(double v) {
  final s = v.toStringAsFixed(2);
  final t = s.contains('.')
      ? s.replaceFirst(RegExp(r'0+$'), '').replaceFirst(RegExp(r'\.$'), '')
      : s;
  return t == '-0' ? '0' : t;
}

// гребни чуть разной высоты: огибающая на три гребня, поэтому весь путь повторяется через три гребня
double _wave(double x, _Layer l, double amp, double phase) =>
    amp *
    (1 + 0.15 * sin(2 * pi * x / (3 * l.length) - phase / 3)) *
    sin(2 * pi * x / l.length - phase);

List<double> _xs(double from, double to, double step) {
  final xs = <double>[];
  for (var x = from; x < to - 1e-9; x += step) {
    xs.add(x);
  }
  return xs..add(to);
}

String _waterPath(_Kind k, _Layer l, List<double> xs,
    double Function(double x) level, double amp, double phase,
    {required double bottom}) {
  final b = StringBuffer();
  for (final (i, x) in xs.indexed) {
    final y = k.h - level(x) * k.h - l.lift - _wave(x, l, amp, phase);
    b.write('${i == 0 ? 'M' : 'L'}${_n(x)},${_n(y)} ');
  }
  b.write('L${_n(xs.last)},${_n(bottom)} L${_n(xs.first)},${_n(bottom)} Z');
  return b.toString();
}

