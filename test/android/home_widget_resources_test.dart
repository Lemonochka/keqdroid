// два одинаковых слоя: новый вид проявляется поверх старого, а старый под ним крутится дальше.
// налив виден только на время перехода, потом на его месте стоячая картинка того же уровня
String _slot(_Kind k, String s) {
  const i = '        ';
  final water = StringBuffer();
  for (final l in _layers.reversed) {
    final tint = l.name == 'back' ? 'primary' : 'primary_container';
    final tag = l.name == 'back' ? 'b' : 'f';
    water.write(_view(
        'ImageView',
        {
          ..._fill('w_${s}_still_$tag'),
          'android:importantForAccessibility': 'no',
          'android:scaleType': 'fitXY',
          'android:src': '@drawable/widget_water_${k.name}_idle_${l.name}',
          'android:tint': '@color/widget_$tint',
        },
        '$i    '));
  }
  for (final st in [_busy, _on]) {
    for (final l in _layers.reversed) {
      final tint = l.name == 'back' ? 'primary' : 'primary_container';
      final tag = l.name == 'back' ? 'b' : 'f';
      water.write(_progress('w_${s}_pour_${st.name}_$tag',
          'widget_water_${k.name}_pour_${st.name}_${l.name}', tint, '$i    '));
    }
  }
  final gone = s == 'b';
  return _view(
    'FrameLayout',
    {
      ..._fill('w_${s}_fade', gone: gone),
      'android:animateLayoutChanges': 'true',
      'android:outlineProvider': 'none',
    },
    '    ',
    _view(
      'FrameLayout',
      {
        ..._fill('w_${s}_slot', gone: gone),
        'android:background': '@drawable/widget_outline',
        'android:clipToOutline': 'true',
      },
      i,
      _view(
            'ImageView',
            {
              ..._fill('w_${s}_bg'),
              'android:importantForAccessibility': 'no',
              'android:scaleType': 'fitXY',
              'android:src': '@drawable/widget_bg',
              'android:tint': '@color/widget_surface_container',
            },
            '$i    ',
          ) +
          water.toString() +
          _content(k, s, '$i    '),
    ),
  );
}

String _layout(_Kind k) => '''
<?xml version="1.0" encoding="utf-8"?>
$_header
<FrameLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@+id/w_root"
    android:layout_width="match_parent"
    android:layout_height="match_parent">
${_slot(k, 'a')}${_slot(k, 'b')}</FrameLayout>
''';

Map<String, String> _generate() {
  final notification =
      File('$_res/drawable/ic_notification.xml').readAsStringSync();
  final logoPaths = RegExp(r'android:pathData="([^"]*)"')
      .allMatches(notification)
      .map((m) => m[1]!)
      .toList();
  return {
    for (final k in _kinds) ...{
      for (final l in _layers) ...{
        for (final st in [_idle, _busy, _on])
          '$_res/drawable/widget_water_${k.name}_${st.name}_${l.name}.xml':
              _stillWater(k, l, st),
        '$_res/drawable/widget_water_${k.name}_pour_busy_${l.name}.xml':
            _pourWater(k, l, _idle, _busy),
        '$_res/drawable/widget_water_${k.name}_pour_on_${l.name}.xml':
            _pourWater(k, l, _busy, _on),
      },
      '$_res/layout/widget_${k.name}.xml': _layout(k),
    },
    '$_res/drawable/widget_logo_loading.xml': _logoLoading(),
    '$_res/drawable/widget_logo_settle.xml': _logoSettle(logoPaths),
    '$_res/values/widget_colors.xml': _colors(),
  };
}

void main() {
  late final Map<String, String> generated;
  setUpAll(() => generated = _generate());

  test('generated widget resources are up to date', () {
    final update = Platform.environment['UPDATE_GOLDEN'] == '1';
    final stale = <String>[];
    for (final e in generated.entries) {
      final file = File(e.key);
      if (update) {
        file.parent.createSync(recursive: true);
        file.writeAsStringSync(e.value);
        continue;
      }
      final actual = file.existsSync()
          ? file.readAsStringSync().replaceAll('\r\n', '\n')
          : null;
      if (actual != e.value) stale.add(e.key);
    }
    expect(stale, isEmpty,
        reason: 'UPDATE_GOLDEN=1 flutter test '
            'test/android/home_widget_resources_test.dart');
  });

  // сборка Windows и апдейтер спотыкаются о не-ASCII в генерируемых файлах
  test('generated files are ASCII only', () {
    for (final e in generated.entries) {
      expect(e.value.runes.every((r) => r < 128), isTrue, reason: e.key);
    }
  });

  // RemoteViews раздувает только классы с @RemoteView: обычный View или Space роняет весь виджет
  test('widget layouts use only views RemoteViews can inflate', () {
    const allowed = {
      'FrameLayout', 'LinearLayout', 'ImageView', 'ProgressBar', 'TextView',
      'Chronometer',
    };
    for (final k in _kinds) {
      final xml = generated['$_res/layout/widget_${k.name}.xml']!;
      final tags = RegExp(r'<([A-Za-z.]+)\s').allMatches(xml).map((m) => m[1]);
      expect(tags.toSet().difference(allowed), isEmpty, reason: k.name);
    }
  });

  test('every view HomeWidget.kt touches exists in a widget layout', () {
    final kotlin = File('$_kotlin/HomeWidget.kt').readAsStringSync();
    final ids = {
      for (final k in _kinds)
        ...RegExp(r'@\+id/(\w+)')
            .allMatches(generated['$_res/layout/widget_${k.name}.xml']!)
            .map((m) => m[1]!),
    };
    final used = RegExp(r'R\.id\.(\w+)').allMatches(kotlin).map((m) => m[1]!);
    expect(used, isNotEmpty);
    expect(used.toSet().difference(ids), isEmpty);
    for (final role in _roles.values) {
      expect(kotlin, contains('"$role"'), reason: role);
    }
  });

  // раньше конца налива стоячая картинка встала бы рывком
  test('the widget swaps the pour for the still picture only after it ends', () {
    final kotlin = File('$_kotlin/HomeWidget.kt').readAsStringSync();
    final settle = RegExp(r'SETTLE_MS = (\d+)L').firstMatch(kotlin);
    expect(settle, isNotNull);
    expect(int.parse(settle![1]!), greaterThan(_pourSeconds * 1000));
  });

  test('Dart sends every color role the widget paints', () {
    final scheme =
        buildPresetScheme(resolveThemePreset('ocean'), Brightness.dark);
    final sent = homeWidgetColors(scheme);
    expect(sent.keys.toSet(), _roles.values.toSet());
    for (final role in _roles.values) {
      expect(sent[role], _role(scheme, role).toARGB32(), reason: role);
    }
  });

  test('widget texts exist in every app language', () {
    final base = File('$_res/values/strings.xml').readAsStringSync();
    final keys = RegExp(r'<string name="(widget_\w+)"')
        .allMatches(base)
        .map((m) => m[1]!)
        .toSet();
    expect(keys, isNotEmpty);
    for (final lang in ['ru', 'de', 'zh', 'fa']) {
      final xml = File('$_res/values-$lang/strings.xml').readAsStringSync();
      for (final key in keys) {
        expect(xml, contains('<string name="$key"'), reason: '$lang $key');
      }
    }
  });
}
